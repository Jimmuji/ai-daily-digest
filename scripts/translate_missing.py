"""
Backfill English digests that are missing or were cut off.

Before the two-pass summarize, the English half shared one 8192-token reply with
the Chinese digest and often got truncated (or never written). This re-translates
the recent days whose daily/<date>.en.md is missing or has fewer items than the
Chinese file, then rebuilds the site (always, so it also republishes
site-only fixes).

Usage: python translate_missing.py --days 7
"""

import argparse
import os
import re
from pathlib import Path

from generate_site import generate_site
from summarize import _wrap, translate_digest

ROOT = Path(__file__).parent.parent
DAILY = ROOT / "daily"


def count_items(md):
    return len(re.findall(r"(?m)^- \*\*", md))


def digest_body(md):
    """The model-written part of a saved digest: drop the '# title' line and the footer."""
    body = re.sub(r"\A# .*\n+", "", md)
    return body.split("\n---\n*Generated by", 1)[0].strip()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--days", type=int, default=7, help="how many recent days to check")
    args = ap.parse_args()

    model = os.environ.get("API_MODEL", "deepseek-chat")
    zh_files = sorted(f for f in DAILY.glob("*.md") if not f.name.endswith(".en.md"))[-args.days:]
    fixed = []
    for zh_file in zh_files:
        date_str = zh_file.stem
        en_file = DAILY / f"{date_str}.en.md"
        zh_md = zh_file.read_text(encoding="utf-8")
        if en_file.exists() and count_items(en_file.read_text(encoding="utf-8")) >= count_items(zh_md):
            continue
        print(f"[backfill] {date_str}: English missing or incomplete, translating...")
        en_text = translate_digest(digest_body(zh_md))
        if not en_text:
            print(f"[backfill] {date_str}: translation failed, left as is.")
            continue
        en_file.write_text(_wrap(en_text, date_str, model, "AI Daily Digest"), encoding="utf-8")
        fixed.append(date_str)

    print(f"[backfill] re-translated: {', '.join(fixed) or 'nothing'}")
    # Rebuild even when nothing was re-translated, so site-only fixes go live too.
    generate_site(root=ROOT)
    print("[backfill] site rebuilt → docs/")


if __name__ == "__main__":
    main()
